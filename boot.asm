; ============================================
; bootloader для LowKey Mini OS
; простой загрузчик, который настраивает сегменты
; и загружает ядро в память
; ============================================

[bits 16]                   ; 16-битный реальный режим
[org 0x7c00]                ; bios загружает сюда

start:
    ; настройка сегментов
    xor ax, ax
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0x7c00          ; стек растёт вниз от загрузчика

    ; вывод сообщения о загрузке
    mov si, msg_boot
    call print_string

    ; загрузка ядра с диска (1 сектор, сразу после загрузчика)
    mov ah, 0x02            ; функция чтения секторов
    mov al, 1               ; количество секторов
    mov ch, 0               ; цилиндр 0
    mov cl, 2               ; сектор 2 (после загрузчика)
    mov dh, 0               ; головка 0
    mov bx, 0x7e00          ; адрес загрузки ядра
    int 0x13

    jc disk_error           ; если ошибка чтения

    ; переход к ядру
    jmp 0x7e00

disk_error:
    mov si, msg_disk_err
    call print_string
    jmp $

; ============================================
; процедура вывода строки
; si - указатель на строку
; ============================================
print_string:
    lodsb                   ; загрузить байт из si в al
    or al, al               ; проверка на конец строки
    jz .done
    mov ah, 0x0e            ; функция вывода символа teletype
    mov bh, 0               ; страница 0
    int 0x10
    jmp print_string
.done:
    ret

msg_boot:       db 'lowkey mini os loading...', 13, 10, 0
msg_disk_err:   db 'disk error!', 13, 10, 0

; заполнение до 512 байт
TIMES 510-($-$$) db 0
dw 0xaa55                   ; сигнатуре загрузочного сектора
